// Generates app/tokens.css from design-system/tokens.json (the ANANDA design system's source of truth).
// Run after updating tokens.json: `pnpm --filter @ananda-agents/web tokens`.
//
// Themes: dark is the default. `data-theme="light"` on <html> switches to light; `data-theme="system"`
// follows the device. The desktop side-panel shadow is mirrored in right-to-left layouts.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const d = JSON.parse(readFileSync(`${root}design-system/tokens.json`, 'utf8'));

const colour = (theme) =>
  d.color.tokens
    .filter((t) => t.value[theme] != null)
    .map((t) => `  --${t.name}: ${t.value[theme]};`)
    .join('\n');
const plain = (group) => d[group].tokens.map((t) => `  --${t.name}: ${t.value};`).join('\n');
const shadowPanel = d.shadow.tokens.find((t) => t.name === 'shadow-panel').value;
const mirrored = shadowPanel.replace(/^(-?)(\d)/, (_, minus, n) => `${minus ? '' : '-'}${n}`);

const styles = d.type.groups.flatMap((g) => g.styles);
const typeClasses = styles
  .map((s) => {
    const extra = s.letterSpacing ? ` letter-spacing: ${s.letterSpacing};` : '';
    return `.${s.name} { font-size: ${s.fontSize}; line-height: ${s.lineHeight}; font-weight: ${s.fontWeight};${extra} }`;
  })
  .join('\n');
const typeVars = styles.map((s) => `  --type-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-sans);`).join('\n');
const font = d.type.fonts[0];

const css = `/* ANANDA design system tokens: generated by scripts/tokens.mjs from design-system/tokens.json
 * (${d.name} v${d.version}). Do not edit by hand. */
@font-face { font-family: "${font.family}"; src: url("/fonts/Rubik-Variable.woff2") format("woff2"); font-weight: ${font.weight}; font-style: ${font.style}; font-display: swap; }

:root, [data-theme="dark"] {
  color-scheme: dark;
${colour('dark')}
}
[data-theme="light"] {
  color-scheme: light;
${colour('light')}
}
@media (prefers-color-scheme: light) {
  [data-theme="system"] {
    color-scheme: light;
${colour('light').replace(/^ {2}/gm, '    ')}
  }
}

:root {
  --font-sans: ${d.type.families.sans};
${plain('paper')}
${plain('spacing')}
${plain('radius')}
${plain('size')}
${plain('shadow')}
${plain('breakpoint')}
${typeVars}
}
[dir="rtl"] { --shadow-panel: ${mirrored}; }

/* Type styles. Overline is upper-case in EN and BG; Hebrew has no upper case or letter-spacing. */
${typeClasses}
.overline { text-transform: uppercase; }
[dir="rtl"] .overline { letter-spacing: 0; }
`;

writeFileSync(`${root}app/tokens.css`, css);
console.log(`tokens.css: ${d.color.tokens.length} colours, ${styles.length} type styles`);
